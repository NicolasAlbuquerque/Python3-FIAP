#FUNÇÃO SOMA
def somar(a,b):
    return  float(a) + float (b)

#FUNÇÃO SUBTRAÇÃO
def subtrair(a,b):
    return float(a) - float(b)

#FUNÇÃO DE DIVISÃO
def dividir(a,b):
    if b == 0:
        return 0
    return float(a) / float (b)

#FUNÇÃO DE MULTIPLICAÇÃO
def multiplicar(a,b):
    return float(a) * float(b)