#Criação da variável com um valor inicial
ii = 10
i = 0

#Enquanto a variavel contadora não chega no limite
while i < 10 :
   #Para cada uma das repetições o bloco é executado
    print(f'Mais uma mensagem, com i valendo {i}')
    i += 1

while ii >= 0:
    print(f'Mais uma mensagem, com ii valendo {ii}')
    ii -= 1